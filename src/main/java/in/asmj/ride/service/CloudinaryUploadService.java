package in.asmj.ride.service;

import com.cloudinary.Cloudinary;
import com.cloudinary.utils.ObjectUtils;
import in.asmj.ride.model.UploadedAsset;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;
import org.springframework.web.multipart.MultipartFile;

import java.util.*;

@Service
public class CloudinaryUploadService {
    @Value("${CLOUDINARY_CLOUD_NAME:}") private String cloudName;
    @Value("${CLOUDINARY_API_KEY:}") private String apiKey;
    @Value("${CLOUDINARY_API_SECRET:}") private String apiSecret;
    @Value("${app.upload.max-bytes:8388608}") private long maxBytes;

    public boolean configured(){return !blank(cloudName)&&!blank(apiKey)&&!blank(apiSecret);}

    public UploadedAsset upload(MultipartFile file, String folder, String category, boolean privateAsset) {
        try {
            validate(file);
            if(!configured()) throw new IllegalStateException("Cloudinary is not configured. Set CLOUDINARY_CLOUD_NAME, CLOUDINARY_API_KEY and CLOUDINARY_API_SECRET.");
            String mime=Optional.ofNullable(file.getContentType()).orElse("application/octet-stream").toLowerCase(Locale.ROOT);
            boolean image=mime.startsWith("image/");
            String resourceType=image?"image":"raw";
            String deliveryType=privateAsset?"authenticated":"upload";
            Map<String,Object> options=new HashMap<>();
            options.put("folder",folder); options.put("resource_type",resourceType); options.put("type",deliveryType);
            options.put("use_filename",true); options.put("unique_filename",true); options.put("overwrite",false);
            Map<?,?> result=(Map<?,?>)client().uploader().upload(file.getBytes(),options);
            UploadedAsset asset=new UploadedAsset();
            asset.setCategory(category); asset.setOriginalFilename(cleanName(file.getOriginalFilename()));
            asset.setPublicId(String.valueOf(result.get("public_id")));
            asset.setSecureUrl(String.valueOf(result.get("secure_url")));
            asset.setResourceType(resourceType); asset.setDeliveryType(deliveryType);
            asset.setContentType(mime); asset.setBytes(file.getSize());
            return asset;
        } catch (Exception ex) {
            throw new IllegalStateException("Cloudinary upload failed: "+safeMessage(ex),ex);
        }
    }

    public void delete(UploadedAsset asset) {
        if(asset==null||blank(asset.getPublicId())||!configured()) return;
        try { client().uploader().destroy(asset.getPublicId(),ObjectUtils.asMap("resource_type",asset.getResourceType(),"type",asset.getDeliveryType(),"invalidate",true)); }
        catch(Exception ex){ throw new IllegalStateException("Could not remove the Cloudinary file: "+safeMessage(ex),ex); }
    }

    /** Signed delivery URL is only generated by server-side views for authorized users. */
    public String deliveryUrl(UploadedAsset asset) {
        if(asset==null) return null;
        if(!"authenticated".equals(asset.getDeliveryType())) return asset.getSecureUrl();
        if(!configured()) return null;
        try { return client().url().secure(true).resourceType(asset.getResourceType()).type(asset.getDeliveryType()).signed(true).generate(asset.getPublicId()); }
        catch(Exception ex){ return null; }
    }

    private Cloudinary client(){return new Cloudinary(ObjectUtils.asMap("cloud_name",cloudName,"api_key",apiKey,"api_secret",apiSecret,"secure",true));}
    private void validate(MultipartFile file) throws Exception{
        if(file==null||file.isEmpty()) throw new IllegalArgumentException("Please select a file to upload.");
        if(file.getSize()>maxBytes) throw new IllegalArgumentException("File is too large. Maximum allowed size is "+(maxBytes/1024/1024)+" MB.");
        String mime=Optional.ofNullable(file.getContentType()).orElse("").toLowerCase(Locale.ROOT);
        String name=Optional.ofNullable(file.getOriginalFilename()).orElse("").toLowerCase(Locale.ROOT);
        boolean image=mime.matches("image/(jpeg|png|webp)") && name.matches(".*\\.(jpg|jpeg|png|webp)$");
        boolean pdf=mime.equals("application/pdf")&&name.endsWith(".pdf");
        if(!image&&!pdf) throw new IllegalArgumentException("Only JPG, PNG, WEBP images and PDF documents are allowed.");
        byte[] bytes=file.getBytes();
        boolean validSignature=pdf ? starts(bytes,new byte[]{0x25,0x50,0x44,0x46})
            : mime.equals("image/jpeg") ? starts(bytes,new byte[]{(byte)0xFF,(byte)0xD8,(byte)0xFF})
            : mime.equals("image/png") ? starts(bytes,new byte[]{(byte)0x89,0x50,0x4E,0x47})
            : bytes.length>=12 && bytes[0]=='R' && bytes[1]=='I' && bytes[2]=='F' && bytes[3]=='F' && bytes[8]=='W' && bytes[9]=='E' && bytes[10]=='B' && bytes[11]=='P';
        if(!validSignature) throw new IllegalArgumentException("The selected file content does not match its file type.");
    }
    private boolean starts(byte[] value,byte[] prefix){if(value.length<prefix.length)return false;for(int i=0;i<prefix.length;i++)if(value[i]!=prefix[i])return false;return true;}
    private boolean blank(String s){return s==null||s.isBlank();}
    private String cleanName(String n){if(n==null)return "upload";return n.replaceAll("[^A-Za-z0-9._-]","_");}
    private String safeMessage(Exception e){return e.getMessage()==null?e.getClass().getSimpleName():e.getMessage().replaceAll("(?i)(api_secret|authorization)[^, ]*","[redacted]");}
}
